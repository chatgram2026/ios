#!/usr/bin/env python3
"""Copies Chitgram's UI strings from the Android app into ChitgramCore.

Android keeps them in org/fenixuz/utils/LanguageCode.kt as TitleLanguages(id, en, uz, ru) and reads them by
position, so the ids are contiguous from 0. iOS uses the same ids, which keeps the two apps comparable line by line.
Run again whenever the Android table grows:

    python3 submodules/ChitgramCore/Tools/import_android_strings.py \
        C:/Users/shohj/Documents/Chatgram/TMessagesProj/src/main/java/org/fenixuz/utils/LanguageCode.kt

The output is a Swift file holding the table as one JSON string (a big array literal would make the type checker
crawl): Sources/ChitgramStringsData.swift.
"""

import json
import os
import re
import sys

LITERAL = r'"(?:[^"\\]|\\.)*"'
EXPRESSION = r'(' + LITERAL + r'(?:\s*\+\s*' + LITERAL + r')*)'
ENTRY = re.compile(
    r'TitleLanguages\(\s*(\d+)\s*,\s*' + EXPRESSION + r'\s*,\s*' + EXPRESSION + r'\s*,\s*' + EXPRESSION + r'\s*\)',
    re.S
)
KOTLIN_ESCAPES = {'"': '"', 'n': '\n', 't': '\t', "'": "'", '$': '$', '\\': '\\'}


def kotlin_string(expression):
    result = []
    for literal in re.findall(LITERAL, expression):
        body = literal[1:-1]
        i = 0
        while i < len(body):
            c = body[i]
            if c == '\\' and i + 1 < len(body):
                n = body[i + 1]
                if n == 'u' and i + 5 < len(body):
                    result.append(chr(int(body[i + 2:i + 6], 16)))
                    i += 6
                    continue
                result.append(KOTLIN_ESCAPES.get(n, n))
                i += 2
                continue
            result.append(c)
            i += 1
    # Emoji are written as UTF-16 surrogate pairs (😀); join them into real characters.
    return ''.join(result).encode('utf-16', 'surrogatepass').decode('utf-16')


def main():
    source_path = sys.argv[1]
    source = open(source_path, encoding='utf-8').read()
    # Whole-line comments sit between the arguments of some entries.
    source = re.sub(r'(?m)^\s*//[^\n]*\n', '', source)

    entries = []
    for match in ENTRY.finditer(source):
        entries.append({
            'id': int(match.group(1)),
            'en': kotlin_string(match.group(2)),
            'uz': kotlin_string(match.group(3)),
            'ru': kotlin_string(match.group(4)),
        })
    ids = [entry['id'] for entry in entries]
    if ids != list(range(len(ids))):
        broken = next(i for i, value in enumerate(ids) if value != i)
        sys.exit('ids are not contiguous from 0: position %d holds id %d' % (broken, ids[broken]))

    # Android writes format arguments Java-style (%1$s, %2$d); Swift's String(format:) reads the same spelling,
    # except that %s takes a C string there. Store %@ so callers pass Swift strings.
    for entry in entries:
        for language in ('en', 'uz', 'ru'):
            entry[language] = re.sub(r'%(\d+\$)?s', lambda m: '%' + (m.group(1) or '') + '@', entry[language])

    table = [[entry['en'], entry['uz'], entry['ru']] for entry in entries]
    payload = json.dumps(table, ensure_ascii=False, separators=(',', ':'))
    if '"""#' in payload:
        sys.exit('the table contains the raw-string terminator')

    here = os.path.dirname(os.path.abspath(__file__))
    output_path = os.path.join(here, '..', 'Sources', 'ChitgramStringsData.swift')
    with open(output_path, 'w', encoding='utf-8', newline='\n') as output:
        output.write('// Generated by Tools/import_android_strings.py from the Android LanguageCode.kt. Do not edit.\n')
        output.write('// %d entries, ids 0...%d, each [en, uz, ru].\n\n' % (len(entries), len(entries) - 1))
        output.write('let chitgramStringsCount = %d\n\n' % len(entries))
        output.write('let chitgramStringsJSON = #"""\n')
        output.write(payload)
        output.write('\n"""#\n')
    print('wrote %d strings to %s' % (len(entries), os.path.normpath(output_path)))


if __name__ == '__main__':
    main()
